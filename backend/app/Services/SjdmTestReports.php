<?php

namespace App\Services;

use App\Models\Agency;
use App\Models\AuditLog;
use App\Models\Incident;
use App\Models\IncidentCategory;
use App\Models\IncidentStatusHistory;
use App\Models\User;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Ramsey\Uuid\Uuid;
use RuntimeException;

class SjdmTestReports
{
    public const REPORTER_EMAIL = 'sjdm-test-reporter@cdrmapp.invalid';

    private const SCENARIOS = [
        'FIRE' => ['Kitchen fire drill', 'Smoke investigation drill', 'Electrical fire drill', 'Grass fire drill', 'Fire evacuation drill'],
        'PNP' => ['Simulated theft report', 'Simulated vandalism report', 'Simulated burglary report', 'Simulated public disturbance', 'Simulated missing bicycle report'],
        'MDRRMO' => ['Flood rescue drill', 'First-aid response drill', 'Fallen tree clearance drill', 'Community evacuation drill', 'Earthquake assessment drill'],
    ];

    public function create(): array
    {
        return DB::transaction(function () {
            $catalog = [];
            foreach (Agency::DEFAULT_NAMES as $type => $name) {
                $agency = Agency::where('type', $type)->where('active', true)->first();
                $category = $agency ? IncidentCategory::where('agency_id', $agency->id)->where('active', true)->orderBy('id')->first() : null;
                if (! $agency || ! $category) {
                    throw new RuntimeException('An active agency and incident category are required for '.$name.'. No test reports were created.');
                }
                $catalog[$type] = [$agency, $category];
            }

            $reporter = User::firstOrNew(['email' => self::REPORTER_EMAIL]);
            if ($reporter->exists && ($reporter->name !== 'SYNTHETIC SJDM test reporter' || $reporter->role !== 'citizen' || $reporter->active)) {
                throw new RuntimeException('The reserved test reporter address is already in use. No accounts or reports were changed.');
            }
            if (! $reporter->exists) {
                $reporter->forceFill([
                    'name' => 'SYNTHETIC SJDM test reporter', 'password' => Str::random(64),
                    'role' => 'citizen', 'active' => false, 'email_verified_at' => now(),
                ])->save();
            }

            $created = 0;
            $slot = 0;
            foreach ($catalog as $type => [$agency, $category]) {
                foreach (self::SCENARIOS[$type] as $index => $scenario) {
                    $key = (string) Uuid::uuid5(Uuid::NAMESPACE_URL, 'https://cdrmapp.com/test-reports/sjdm/v1/'.$type.'/'.$index);
                    $existing = Incident::where('reporter_id', $reporter->id)->where('idempotency_key', $key)->first();
                    // A permutation distributes all agencies across fifteen separate cells.
                    $cell = ($slot++ * 7) % 15;
                    if ($existing) {
                        if (! $existing->is_test) {
                            throw new RuntimeException('An existing fixture is no longer marked as test data. No reports were changed.');
                        }

                        continue;
                    }
                    $payload = [
                        'reporter_id' => $reporter->id, 'agency_id' => $agency->id, 'category_id' => $category->id,
                        'public_reference' => (string) Str::uuid(), 'idempotency_key' => $key,
                        'description' => '[TEST REPORT — NOT A REAL EMERGENCY] '.$scenario.'. Synthetic report '.($index + 1).' of 5 for '.$agency->name.' in San Jose del Monte, Bulacan.',
                        // Interior SJDM grid; each point varies by at most ~110 m.
                        'latitude' => round(14.806 + intdiv($cell, 5) * 0.009 + random_int(-1000, 1000) / 1000000, 6),
                        'longitude' => round(121.039 + ($cell % 5) * 0.009 + random_int(-1000, 1000) / 1000000, 6),
                        'location_source' => 'manual', 'address' => 'SYNTHETIC location — San Jose del Monte, Bulacan',
                        'received_at' => now()->subSeconds(random_int(0, 1800)),
                        'workflow_status' => 'submitted', 'verification_status' => 'unverified', 'is_test' => true,
                    ];
                    $incident = Incident::create($payload + ['request_hash' => hash('sha256', json_encode($payload))]);
                    IncidentStatusHistory::create([
                        'incident_id' => $incident->id, 'actor_id' => $reporter->id, 'new_status' => 'submitted',
                        'note' => 'SYNTHETIC TEST: generated by the SJDM test-data command. No real emergency or notification.',
                    ]);
                    AuditLog::recordChange($reporter, 'incident.test_created', $incident, [], [
                        'agency' => $agency->name, 'description' => $incident->description, 'is_test' => true,
                    ], '[TEST] '.$agency->name.' — '.$incident->public_reference);
                    $created++;
                }
            }

            // Deliberately bypass IncidentWorkflow::notify: fixtures never send alerts.
            return ['created' => $created, 'existing' => 15 - $created, 'total' => 15];
        });
    }
}
